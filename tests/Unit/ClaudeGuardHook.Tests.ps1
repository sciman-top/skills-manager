BeforeAll {
    $script:RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).ProviderPath
    $script:Hook = Join-Path $script:RepoRoot '.claude\hooks\guard-generated.ps1'
    function Invoke-Guard([string]$Json) {
        $null = $Json | & pwsh -NoProfile -File $script:Hook 2>&1
        return $LASTEXITCODE
    }
    function New-EditEvent([string]$FilePath) {
        return (@{ tool_input = @{ file_path = $FilePath } } | ConvertTo-Json -Compress)
    }
}

Describe 'Claude PreToolUse guard blocks direct edits to generated paths' {
    It 'blocks the generated thin entry skills.ps1' {
        Invoke-Guard (New-EditEvent 'skills.ps1') | Should -Be 2
    }

    It 'blocks generated library files addressed by absolute path' {
        $absolute = Join-Path $script:RepoRoot 'skills.lib\Main.ps1'
        Invoke-Guard (New-EditEvent $absolute) | Should -Be 2
    }

    It 'blocks materialized agent, vendor and import directories' {
        Invoke-Guard (New-EditEvent 'agent/demo/SKILL.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'vendor/demo/README.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'imports/demo/a.md') | Should -Be 2
    }

    It 'blocks generated host global rule files' {
        Invoke-Guard (New-EditEvent 'rules/global/claude/CLAUDE.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'rules/global/codex/AGENTS.md') | Should -Be 2
    }
}

Describe 'Claude PreToolUse guard allows source and unrelated edits' {
    It 'allows source edits, which are regenerated by build.ps1' {
        Invoke-Guard (New-EditEvent 'src/Main.ps1') | Should -Be 0
    }

    It 'allows the global rule source files' {
        Invoke-Guard (New-EditEvent 'rules/global/common.md') | Should -Be 0
        Invoke-Guard (New-EditEvent 'rules/global/platforms/claude.md') | Should -Be 0
    }

    It 'does not block look-alike names that are not generated' {
        Invoke-Guard (New-EditEvent 'skills.ps1.bak') | Should -Be 0
    }
}

Describe 'Claude PreToolUse guard fails open on input it cannot interpret' {
    It 'allows malformed JSON' {
        Invoke-Guard 'not json' | Should -Be 0
    }

    It 'allows events without a file path' {
        Invoke-Guard '{}' | Should -Be 0
    }
}
