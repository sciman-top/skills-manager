BeforeAll {
    $script:RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).ProviderPath
    $script:Hook = Join-Path $script:RepoRoot 'scripts\guard-generated.ps1'
    function New-BashEvent([string]$Command) {
        return (@{ tool_input = @{ command = $Command } } | ConvertTo-Json -Compress)
    }
    function New-PatchEvent([string[]]$Lines) {
        $patch = (@('*** Begin Patch') + $Lines + @('*** End Patch')) -join "`n"
        return (@{ tool_input = @{ patch = $patch } } | ConvertTo-Json -Compress)
    }
    function New-EditEvent([string]$FilePath) {
        return (@{ tool_input = @{ file_path = $FilePath } } | ConvertTo-Json -Compress)
    }
    # Pester 4 + PowerShell 7 + 中文 Windows：函数间直接管道传参会按 ANSI 代码页
    # 转码（实测"全部"变"鍏ㄩ儴"），守卫用 -match 判定证据时会误判。改为经
    # Set-Content 写 UTF-8 文件再用 -RedirectStandardInput 送入 stdin，得到真实
    # 字节流，同时覆盖 hook 在宿主上实际收到的编码。
    function Invoke-WithEvent([string]$EventPath, [string]$HookPath) {
        $outPath = Join-Path ([IO.Path]::GetTempPath()) ('guardout-' + [guid]::NewGuid().ToString('N') + '.txt')
        $errPath = Join-Path ([IO.Path]::GetTempPath()) ('guarderr-' + [guid]::NewGuid().ToString('N') + '.txt')
        try {
            $process = Start-Process -FilePath (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile', '-File', $HookPath) `
                -RedirectStandardInput $EventPath -RedirectStandardOutput $outPath -RedirectStandardError $errPath -NoNewWindow -PassThru -Wait
            return [pscustomobject]@{
                exit_code = $process.ExitCode
                stdout    = if (Test-Path -LiteralPath $outPath) { [IO.File]::ReadAllText($outPath) } else { '' }
                stderr    = if (Test-Path -LiteralPath $errPath) { [IO.File]::ReadAllText($errPath) } else { '' }
            }
        }
        finally {
            Remove-Item -LiteralPath $outPath, $errPath -ErrorAction SilentlyContinue
        }
    }
    function Invoke-Guard([string]$Json) {
        $eventPath = Join-Path ([IO.Path]::GetTempPath()) ('guarde-' + [guid]::NewGuid().ToString('N') + '.json')
        try {
            Set-Content -LiteralPath $eventPath -Value $Json -Encoding utf8 -NoNewline
            return (Invoke-WithEvent $eventPath $script:Hook).exit_code
        }
        finally {
            Remove-Item -LiteralPath $eventPath -ErrorAction SilentlyContinue
        }
    }
}

Describe 'Panel guard blocks direct edits to generated paths' {
    It 'blocks the generated thin entry skills.ps1' {
        Invoke-Guard (New-EditEvent 'skills.ps1') | Should -Be 2
    }

    It 'blocks generated library files addressed by absolute path' {
        $absolute = Join-Path $script:RepoRoot 'skills.lib\Main.ps1'
        Invoke-Guard (New-EditEvent $absolute) | Should -Be 2
    }

    It 'blocks materialized agent, vendor and import directories' {
        Invoke-Guard (New-EditEvent 'agent/demo/SKILL.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'vendor/demo/README.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'imports/demo/a.md') | Should -Be 2
    }

    It 'blocks generated host global rule files for every registered host' {
        Invoke-Guard (New-EditEvent 'rules/global/claude/CLAUDE.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'rules/global/codex/AGENTS.md') | Should -Be 2
        Invoke-Guard (New-EditEvent 'rules/global/dsh/AGENTS.md') | Should -Be 2
    }
}

Describe 'Panel guard allows source and unrelated edits' {
    It 'allows source edits, which are regenerated by build.ps1' {
        Invoke-Guard (New-EditEvent 'src/Main.ps1') | Should -Be 0
        Invoke-Guard (New-EditEvent 'scripts/guard-generated.ps1') | Should -Be 0
    }

    It 'allows the global rule source files' {
        Invoke-Guard (New-EditEvent 'rules/global/common.md') | Should -Be 0
        Invoke-Guard (New-EditEvent 'rules/global/platforms/claude.md') | Should -Be 0
    }

    It 'does not block look-alike names that are not generated' {
        Invoke-Guard (New-EditEvent 'skills.ps1.bak') | Should -Be 0
    }
}

Describe 'Panel guard fails open on input it cannot interpret' {
    It 'allows malformed JSON' {
        Invoke-Guard 'not json' | Should -Be 0
    }

    It 'allows events without a file path, patch or command' {
        Invoke-Guard '{}' | Should -Be 0
        Invoke-Guard '{"tool_input":{}}' | Should -Be 0
    }
}

Describe 'Panel guard blocks Bash writes to generated paths' {
    It 'blocks a redirection into a materialized directory' {
        Invoke-Guard (New-BashEvent 'echo x > agent/demo/SKILL.md') | Should -Be 2
    }

    It 'blocks an in-place edit of the generated thin entry' {
        Invoke-Guard (New-BashEvent "sed -i 's/a/b/' skills.ps1") | Should -Be 2
        Invoke-Guard (New-BashEvent 'sed -i.bak s/a/b/ agent/README.md') | Should -Be 2
        Invoke-Guard (New-BashEvent 'sed --in-place s/a/b/ vendor/demo/README.md') | Should -Be 2
    }

    It 'blocks removing or copying generated directories' {
        Invoke-Guard (New-BashEvent 'Remove-Item agent/demo -Recurse -Force') | Should -Be 2
        Invoke-Guard (New-BashEvent 'git rm skills.lib/Core.ps1') | Should -Be 2
        Invoke-Guard (New-BashEvent 'Copy-Item x.md vendor/demo/README.md') | Should -Be 2
    }

    It 'blocks git subcommands that revert or restage generated trees' {
        # 这些子命令能整体切换受管路径、回退已授权改动，v1 纳入 guard。
        Invoke-Guard (New-BashEvent 'git checkout -- skills.lib/Core.ps1') | Should -Be 2
        Invoke-Guard (New-BashEvent 'git restore --staged agent/demo/SKILL.md') | Should -Be 2
        Invoke-Guard (New-BashEvent 'git clean -fd rules/global/dsh') | Should -Be 2
    }
}

Describe 'Panel guard allows Bash commands that do not write generated paths' {
    It 'allows read-only access to generated files' {
        Invoke-Guard (New-BashEvent 'cat skills.lib/Core.ps1') | Should -Be 0
        Invoke-Guard (New-BashEvent 'git diff -- skills.lib/Core.ps1') | Should -Be 0
    }

    It 'allows read-only sed on generated files, which is not an in-place write' {
        Invoke-Guard (New-BashEvent 'sed -n 1,5p agent/README.md') | Should -Be 0
        Invoke-Guard (New-BashEvent "sed -n '1,20p' vendor/readme.txt | head -5") | Should -Be 0
    }

    It 'allows read-only git history commands over generated paths' {
        Invoke-Guard (New-BashEvent 'git log --oneline -3 -- skills.ps1') | Should -Be 0
        Invoke-Guard (New-BashEvent 'git show HEAD:skills.lib/Core.ps1') | Should -Be 0
    }

    It 'allows the build and generated-tree verification commands' {
        Invoke-Guard (New-BashEvent 'pwsh -NoProfile -File ./build.ps1 -Check') | Should -Be 0
        Invoke-Guard (New-BashEvent 'pwsh -NoProfile -File ./skills.ps1 构建生效 > reports/out.log 2>&1') | Should -Be 0
    }

    It 'allows writes to unrelated paths' {
        Invoke-Guard (New-BashEvent 'echo hi > docs/note.md') | Should -Be 0
        Invoke-Guard (New-BashEvent 'Remove-Item reports/tmp -Recurse') | Should -Be 0
    }

    It 'allows a git subcommand that only names a non-generated path' {
        Invoke-Guard (New-BashEvent 'git checkout -- src/Main.ps1') | Should -Be 0
    }
}

Describe 'Panel guard handles the Codex apply_patch payload' {
    It 'blocks a generated edit that carries no source change in the same patch' {
        Invoke-Guard (New-PatchEvent @('*** Update File: skills.lib/Core.ps1')) | Should -Be 2
        Invoke-Guard (New-PatchEvent @('*** Add File: rules/global/dsh/AGENTS.md', '+text')) | Should -Be 2
    }

    It 'allows a generated edit batched with its source rebuild' {
        Invoke-Guard (New-PatchEvent @('*** Update File: src/Core.ps1', '*** Update File: skills.lib/Core.ps1')) | Should -Be 0
    }

    It 'allows removing a generated file, which needs no source change' {
        Invoke-Guard (New-PatchEvent @('*** Delete File: agent/demo/SKILL.md')) | Should -Be 0
    }

    It 'ignores patches that touch no guarded path' {
        Invoke-Guard (New-PatchEvent @('*** Update File: docs/product/README.md')) | Should -Be 0
    }
}

Describe 'Panel guard registration is shared by both hosts' {
    It 'registers the shared guard script from Claude settings with Edit, MultiEdit, Write and Bash' {
        $settings = Get-Content -LiteralPath (Join-Path $script:RepoRoot '.claude\settings.json') -Raw | ConvertFrom-Json
        $matchers = @($settings.hooks.PreToolUse | ForEach-Object { [string]$_.matcher })
        $matchers | Should -Contain 'Edit|MultiEdit|Write|Bash'
        $command = [string]$settings.hooks.PreToolUse[0].hooks[0].command
        $command | Should -Match 'scripts/guard-generated\.ps1'
        $command | Should -Match '\$\{CLAUDE_PROJECT_DIR\}'
        $command | Should -Not -Match '(?<!\{)\$CLAUDE_PROJECT_DIR\b'
    }

    It 'resolves the Claude command to a file that exists' {
        $settings = Get-Content -LiteralPath (Join-Path $script:RepoRoot '.claude\settings.json') -Raw | ConvertFrom-Json
        $expanded = ([string]$settings.hooks.PreToolUse[0].hooks[0].command).Replace('${CLAUDE_PROJECT_DIR}', $script:RepoRoot.Replace('\', '/'))
        $filePathMatch = [regex]::Match($expanded, '-File\s+"([^"]+)"')
        $filePathMatch.Success | Should -BeTrue
        Test-Path $filePathMatch.Groups[1].Value | Should -BeTrue
    }

    It 'registers the same guard script for Codex Bash and apply_patch, resolving from the git root' {
        $configPath = Join-Path $script:RepoRoot '.codex\config.toml'
        $config = Get-Content -LiteralPath $configPath -Raw
        $config | Should -Match '(?m)^\[\[hooks\.PreToolUse\]\]'
        $config | Should -Match 'matcher = "\^Bash\$"'
        $config | Should -Match 'matcher = "\^apply_patch\$"'
        @([regex]::Matches($config, 'guard-generated\.ps1')).Count | Should -BeGreaterOrEqual 2
        $config | Should -Not -Match "pwsh -NoProfile -File '?\./"
        $config | Should -Match 'git rev-parse --show-toplevel'
    }

    It 'keeps a single guard script copy in the repository' {
        $copies = @(Get-ChildItem -LiteralPath $script:RepoRoot -Recurse -File -Filter 'guard-generated.ps1' -ErrorAction SilentlyContinue |
                Where-Object { $_.FullName -notmatch '\\(?:vendor|imports|agent|\.claude\\worktrees|\.txn|node_modules)\\' })
        @($copies).Count | Should -Be 1
    }
}
